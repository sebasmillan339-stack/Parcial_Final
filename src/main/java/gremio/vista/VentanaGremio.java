    // Cambia la etiqueta, la ficha didáctica y el campo según la clase elegida
    public void mostrarCampoSegunClase(String clase) {
        boolean esSiNo = clase.equals("Guerrero") || clase.equals("Pícaro");
        chkSiNo.setVisible(esSiNo);
        txtAtributo.setVisible(!esSiNo);

        String etiqueta, icono, descripcion;
        Color color;
        switch (clase) {
            case "Guerrero":
                etiqueta = "Armadura"; icono = "⚔"; color = new Color(0xE0574A);
                chkSiNo.setText("Sí, armadura pesada");
                descripcion = "Maestro de las armas: aguanta golpes y ataca varias veces por turno. Marca la casilla si lleva armadura pesada.";
                break;
            case "Mago":
                etiqueta = "Espacios de conjuro"; icono = "✦"; color = new Color(0xB48CE6);
                descripcion = "Lanza conjuros devastadores, pero cada uno gasta un espacio de conjuro. Escribe cuántos tiene (número entero).";
                break;
            case "Clérigo":
                etiqueta = "Dios venerado"; icono = "✚"; color = new Color(0xE6C65C);
                descripcion = "Sirviente de un dios: cura a sus aliados y expulsa muertos vivientes. Escribe el nombre del dios que venera.";
                break;
            case "Monje":
                etiqueta = "Puntos de Ki"; icono = "☯"; color = new Color(0x3CC49A);
                descripcion = "Combate con las manos vacías usando su energía interior. Escribe sus puntos de Ki (número entero).";
                break;
            case "Paladín":
                etiqueta = "Puntos de fuerza"; icono = "⚜"; color = new Color(0xE8D9A0);
                descripcion = "Guerrero sagrado que gasta magia para golpear con Castigo Divino. Escribe sus puntos de fuerza (número entero).";
                break;
            case "Explorador":
                etiqueta = "Terreno favorecido"; icono = "☘"; color = new Color(0x6FCF7F);
                descripcion = "Cazador experto que marca a su presa para hacerle daño continuo. Escribe su terreno favorito (por ejemplo: Bosque).";
                break;
            case "Pícaro":
                etiqueta = "Herramientas"; icono = "☠"; color = new Color(0xB8C2D0);
                chkSiNo.setText("Sí, las tiene");
                descripcion = "Ágil y sigiloso: ataca por sorpresa con daño masivo y se reposiciona. Marca la casilla si tiene herramientas de ladrón.";
                break;
            default: // Bardo
                etiqueta = "Instrumento"; icono = "♫"; color = new Color(0xF08FC0);
                descripcion = "Músico que inspira a sus aliados con su arte. Escribe su instrumento musical (por ejemplo: Laúd).";
        }
        lblAtributo.setText(etiqueta);
        lblNombreClase.setText(clase);
        lblIconoClase.setText(icono);
        lblIconoClase.setForeground(color);
        txtDescClase.setText(descripcion);
    }

