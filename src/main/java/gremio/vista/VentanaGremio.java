    // Tarjetas de colores con cuántos héroes hay de cada clase (el orden del arreglo es el de las tarjetas)
    public void actualizarContadores(int[] c) {
        lblContGuerrero.setText(tarjeta("⚔", "Guerreros", c[0]));
        lblContMago.setText(tarjeta("✦", "Magos", c[1]));
        lblContClerigo.setText(tarjeta("✚", "Clérigos", c[2]));
        lblContMonje.setText(tarjeta("☯", "Monjes", c[3]));
        lblContPaladin.setText(tarjeta("⚜", "Paladines", c[4]));
        lblContExplorador.setText(tarjeta("☘", "Exploradores", c[5]));
        lblContPicaro.setText(tarjeta("☠", "Pícaros", c[6]));
        lblContBardo.setText(tarjeta("♫", "Bardos", c[7]));
    }

    private String tarjeta(String icono, String titulo, int cantidad) {
        return "<html><div style='text-align:center'>" + icono + " " + titulo
                + "<br><span style='font-size:13pt'>" + cantidad + "</span></div></html>";
    }

